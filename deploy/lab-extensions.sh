#!/usr/bin/env bash
# Mira Voice — lab test extensions (task 0.3), until Mira Core manages extensions (Phase 1).
#
#   sudo ./deploy/lab-extensions.sh            create 1001-1004 if missing, show the credentials
#   sudo ./deploy/lab-extensions.sh --rotate   new passwords for all of them
#
# Each extension gets a random password (no default passwords). Credentials are kept in
# /opt/mira/config/lab-extensions.txt (root only). Test numbers: 600 echo, 601 hello world,
# 602 hello world in French, 1001-1004 call each other.
set -Eeuo pipefail

MIRA_DIR=/opt/mira
CONF="$MIRA_DIR/config/asterisk/pjsip_lab.conf"
CREDS="$MIRA_DIR/config/lab-extensions.txt"
EXTENSIONS="1001 1002 1003 1004"

die() {
	printf 'ERROR: %s\n' "$*" >&2
	exit 1
}
[ "$(id -u)" -eq 0 ] || die "run as root: sudo $0"
[ -f "$MIRA_DIR/.env" ] || die "Mira is not installed (run deploy/install.sh first)"

ROTATE=0
case "${1:-}" in
--rotate) ROTATE=1 ;;
"") ;;
*) die "unknown option: $1" ;;
esac

domain=$(sed -n 's/^MIRA_SIP_DOMAIN=//p' "$MIRA_DIR/.env" | tail -1)

if [ ! -s "$CONF" ] || [ "$ROTATE" -eq 1 ]; then
	umask 077
	tmp_conf=$(mktemp) tmp_creds=$(mktemp)
	{
		echo "; Mira Voice lab extensions — generated by deploy/lab-extensions.sh on $(date -u +%F)."
		echo "; Do not edit; re-run the script. Replaced by Mira Core-managed endpoints in Phase 1."
	} >"$tmp_conf"
	printf '%-6s %-34s %s\n' "EXT" "PASSWORD" "SIP URI" >"$tmp_creds"
	for ext in $EXTENSIONS; do
		pw=$(openssl rand -hex 16)
		cat >>"$tmp_conf" <<-EOF

			[$ext](mira-endpoint)
			auth = $ext-auth
			aors = $ext
			callerid = "Lab $ext" <$ext>

			[$ext-auth](mira-auth)
			username = $ext
			password = $pw

			[$ext](mira-aor)
		EOF
		printf '%-6s %-34s sip:%s@%s\n' "$ext" "$pw" "$ext" "$domain" >>"$tmp_creds"
	done
	install -m 0600 -o root -g root "$tmp_conf" "$CONF"
	install -m 0600 -o root -g root "$tmp_creds" "$CREDS"
	rm -f "$tmp_conf" "$tmp_creds"
	echo "Lab extensions written; restarting Asterisk to load them..."
	(cd "$MIRA_DIR" && docker compose restart asterisk >/dev/null)
fi

cat <<EOF

Mira Voice lab extensions (also in $CREDS, root only)
-------------------------------------------------------------------------------
$(cat "$CREDS")
-------------------------------------------------------------------------------
Server / domain : $domain
Transports      : UDP or TCP $domain:5060  |  TLS $domain:5061 (SRTP)  |  WSS wss://$domain:8089
Test numbers    : 600 echo test, 601 hello world, 602 French, 1001-1004 each other
EOF
