T1 = uuid.UUID("11111111-2222-3333-4444-555555555555")


def test_dialplan_has_one_context_per_tenant() -> None:
    out = render_dialplan(
        [
            DialplanTenant("acme", tenant_context(T1), [DialplanExtension("1001", "acme-1001")]),
            DialplanTenant("empty", "t_" + "0" * 32),
        ],
        generated_at=datetime(2026, 11, 25, tzinfo=UTC),
    )
    assert out.startswith("; GENERATED by Mira Core from the database (2026-11-25 00:00:00Z)")
    assert "[t_11111111222233334444555555555555]" in out
    assert "exten => 1001,1,Gosub(mira-dial-extension,s,1(acme-1001))\n same => n,Hangup()" in out
    # every tenant context and every inbound context ends with the unknown-number fallback
    assert out.count("exten => _X.,1,Gosub(mira-unknown-number,s,1)") == 4
    assert "[t_11111111222233334444555555555555_in]" in out


