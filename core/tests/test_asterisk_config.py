def test_write_only_when_content_changes(tmp_path: Path) -> None:
    t = [DialplanTenant("acme", tenant_context(T1), [DialplanExtension("1001", "acme-1001")])]
    first = render_dialplan(t, datetime(2026, 1, 1, tzinfo=UTC))
    later_same = render_dialplan(t, datetime(2026, 1, 2, tzinfo=UTC))  # only the stamp differs
    assert write_atomically(tmp_path, "x.conf", first) is True
    assert write_atomically(tmp_path, "x.conf", later_same) is False  # no pointless reload
    t[0].extensions.append(DialplanExtension("1002", "acme-1002"))
    assert write_atomically(tmp_path, "x.conf", render_dialplan(t)) is True
    assert (tmp_path / "x.conf").stat().st_mode & 0o777 == 0o644
    assert not list(tmp_path.glob(".x.conf.*"))  # no temp files left behind


def test_secret_files_are_not_world_readable(tmp_path: Path) -> None:
    write_atomically(tmp_path, "pjsip_mira.conf", "x\n", mode=0o640)
    assert (tmp_path / "pjsip_mira.conf").stat().st_mode & 0o777 == 0o640


# ---- trunks and routes (task 1.2) ----

K1 = uuid.UUID("aaaaaaaa-0000-0000-0000-000000000001")
K2 = uuid.UUID("aaaaaaaa-0000-0000-0000-000000000002")
TRUNK1 = "trunk_" + K1.hex
TRUNK2 = "trunk_" + K2.hex


def pjsip_trunk(kind: TrunkKind = TrunkKind.SIP_IP_AUTH, **kw: object) -> PjsipTrunk:
    values: dict[str, object] = {
        "endpoint": TRUNK1,
        "kind": kind,
        "tenant_id": T1,
        "context": inbound_context(T1, K1),
        "language": "en",
        "host": "203.0.113.10",
        "port": 5060,
        "transport": "udp",
        "auth_username": None,
        "secret": None,
        "from_domain": None,
        "sip_ha1": None,
        "inbound_ips": [],
    }
    values.update(kw)
    return PjsipTrunk(**values)  # type: ignore[arg-type]


def test_outbound_route_tries_trunks_in_order_with_caller_id() -> None:
    steps = [RouteStep(TRUNK1, "+20225550000"), RouteStep(TRUNK2, "")]
    tenant = DialplanTenant(
        "acme", tenant_context(T1), routes=[DialplanRoute("0Z.", 1, "+20", steps)]
    )
    out = render_dialplan([tenant])
    expected = (
        f"exten => _0Z.,1,Gosub(mira-outbound,s,1(+20${{EXTEN:1}},{TRUNK1},+20225550000,{TRUNK2},))"
    )
    assert expected in out


def test_inbound_routes_per_trunk_fall_back_to_tenant_wide() -> None:
    ctx = tenant_context(T1)
    tenant = DialplanTenant(
        "acme",
        ctx,
        [DialplanExtension("1001", "acme-1001"), DialplanExtension("1002", "acme-1002")],
        inbound=[DialplanInbound("*", "1001")],
        trunks=[
            DialplanTrunk(
                TRUNK1, inbound_context(T1, K1), [DialplanInbound("+20225550001", "1002")]
            )
        ],
    )
    out = render_dialplan([tenant])
    tenant_in = out.split(f"[{ctx}_in]\n", 1)[1].split("\n[", 1)[0]
    assert f"exten => _X.,1,Goto({ctx},1001,1)" in tenant_in
    assert f"exten => _+X.,1,Goto({ctx},1001,1)" in tenant_in
    assert "mira-unknown-number" not in tenant_in  # "*" catches everything
    trunk_in = out.split(f"[{inbound_context(T1, K1)}]\n", 1)[1]
    assert f"exten => +20225550001,1,Goto({ctx},1002,1)" in trunk_in
    assert f"include => {ctx}_in" in trunk_in


