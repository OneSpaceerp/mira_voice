def test_registering_trunk_renders_auth_and_registration() -> None:
    out = render_pjsip(
        [
            pjsip_trunk(
                TrunkKind.SIP_REGISTER,
                host="sip.we.example",
                auth_username="0225550000",
                secret=r"s3cr;et\x",
                from_domain="we.example",
            )
        ]
    )
    assert f"[{TRUNK1}]\ntype = endpoint" in out
    assert r"outbound_proxy = sip:127.0.0.1:5060\;lr" in out
    assert f"outbound_auth = {TRUNK1}-out" in out
    assert r"password = s3cr\;et\\x" in out  # ';' and '\' escaped
    assert f"[{TRUNK1}-reg]\ntype = registration" in out
    assert "server_uri = sip:sip.we.example:5060\n" in out
    assert "client_uri = sip:0225550000@we.example" in out
    assert f"contact_user = {TRUNK1}" in out
    # Asterisk 22 refuses a registration with "endpoint" unless line support is on
    assert "\nendpoint =" not in out.split(f"[{TRUNK1}-reg]")[1]
    assert f"match_header = X-Mira-Trunk: {TRUNK1}" in out
    assert f"context = {inbound_context(T1, K1)}" in out


def test_tls_trunk_contact_carries_the_transport() -> None:
    out = render_pjsip([pjsip_trunk(host="sip.example", port=5061, transport="tls")])
    assert r"contact = sip:sip.example:5061\;transport=tls" in out
    assert "registration" not in out and "outbound_auth" not in out  # IP-auth, no password


def test_gsm_gateway_is_a_registering_device() -> None:
    out = render_pjsip([pjsip_trunk(TrunkKind.GSM_GATEWAY, host="dynamic", sip_ha1="b" * 32)])
    assert f"auth = {TRUNK1}-in" in out
    assert "password_digest = MD5:" + "b" * 32 in out
    assert "max_contacts = 1" in out
    assert "outbound_proxy" not in out and "registration" not in out and "identify" not in out


