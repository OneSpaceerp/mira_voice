#!/bin/sh
# Mira Voice — Kamailio container entrypoint.
# Renders kamailio.cfg from environment variables, installs the TLS certificate from the
# read-only host mount, checks the config, then runs Kamailio as the "kamailio" user.
set -eu

: "${MIRA_LOCAL_IP:?MIRA_LOCAL_IP is not set}"
: "${MIRA_PUBLIC_IP:?MIRA_PUBLIC_IP is not set}"
: "${MIRA_SIP_DOMAIN:?MIRA_SIP_DOMAIN is not set}"
: "${KAMAILIO_RPC_TOKEN:?KAMAILIO_RPC_TOKEN is not set}"

umask 027
# shellcheck disable=SC2016 # envsubst takes the literal variable names as its list
envsubst '${MIRA_LOCAL_IP} ${MIRA_PUBLIC_IP} ${MIRA_SIP_DOMAIN} ${KAMAILIO_RPC_TOKEN}' \
	</etc/kamailio/kamailio.cfg.tmpl >/etc/kamailio/kamailio.cfg
# holds the RPC token: not world-readable
chown root:kamailio /etc/kamailio/kamailio.cfg
chmod 0640 /etc/kamailio/kamailio.cfg

# Carrier list generated by Mira Core (shared volume, task 1.2). Without it (Core not run yet)
# the built-in list with only the local Asterisk is used, and trunks are not recognised.
generated=/etc/kamailio/generated/dispatcher.list
if [ -s "$generated" ]; then
	ln -sf "$generated" /etc/kamailio/dispatcher.list
else
	echo "WARNING: $generated missing: no carrier trunks until Mira Core writes it" >&2
fi

# TLS certificate and key: host file /opt/mira/config/tls/{mira.crt,mira.key} (root only).
src=/run/mira-config/tls
[ -s "$src/mira.crt" ] && [ -s "$src/mira.key" ] || {
	echo "ERROR: TLS certificate missing in $src (deploy/install.sh creates it)" >&2
	exit 1
}
install -d -m 0750 -o root -g kamailio /etc/kamailio/tls
install -m 0640 -o root -g kamailio "$src/mira.crt" /etc/kamailio/tls/mira.crt
install -m 0640 -o root -g kamailio "$src/mira.key" /etc/kamailio/tls/mira.key

install -d -m 0750 -o kamailio -g kamailio /run/kamailio

kamailio -c -f /etc/kamailio/kamailio.cfg

exec kamailio -DD -E -f /etc/kamailio/kamailio.cfg -u kamailio -g kamailio -m 256 -M 32
